"""Table of the CPM label distribution of the single-attacker and the coordinated collections (tab:attack-distribution),
from the cache summaries written by `python -m gencpm cache`."""

import argparse
import json
from pathlib import Path

SINGLE = [("AddObjectAttack", "CF"), ("RemoveObjectAttack", "CS"), ("DriftAttack", "CSD"), ("WhiteNoiseAttack", "ISP"),
          ("GhostTrackAttack", "GT"), ("StealthDriftAttack", "SD"), ("ReplayAttack", "RP"),
          ("PoseFalsificationAttack", "PF")]
COORD = [("ColludingGhostAttack", "CG"), ("CoordinatedSuppressionAttack", "CSUP"), ("CoordinatedDriftAttack", "CCSD"),
         ("CoordinatedISPAttack", "CISP")]


def _n(x):
    return f"{x:,}".replace(",", "{,}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--work", required=True, help="work dir of the single-attacker collection")
    ap.add_argument("--coord-work", required=True, help="work dir of the coordinated collection")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    cs = json.loads((Path(a.work) / "cache_summary.json").read_text())["attack_counts"]
    cc = json.loads((Path(a.coord_work) / "cache_summary.json").read_text())["attack_counts"]
    ts, tc = sum(cs.values()), sum(cc.values())
    left = [("Benign", cs.get("", 0))] + [(s, cs.get(k, 0)) for k, s in SINGLE]
    right = [("Benign", cc.get("", 0))] + [(s, cc.get(k, 0)) for k, s in COORD]
    rows = []
    for i, (s, v) in enumerate(left):
        r = f"{s} & {_n(v)} & {100 * v / ts:.1f} & "
        r += f"{right[i][0]} & {_n(right[i][1])} & {100 * right[i][1] / tc:.1f}" if i < len(right) else "& &"
        rows.append(r + r" \\")
    out = [r"% Auto-generated by gencpm.report.distribution -- do not edit by hand.",
           r"\begin{table}[t]", r"\centering", r"\caption{Distribution of CPM labels.}", r"\label{tab:attack-distribution}",
           r"\footnotesize", r"\setlength{\tabcolsep}{0pt}",
           r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}} l r r l r r}", r"\toprule",
           r"\multicolumn{3}{c}{\textbf{One attacker}} & \multicolumn{3}{c}{\textbf{Coordinated}} \\",
           r"\cmidrule(lr){1-3}\cmidrule(lr){4-6}", r" & \#CPMs & \% & & \#CPMs & \% \\", r"\midrule", *rows,
           r"\midrule", f"Total & {_n(ts)} & 100 & Total & {_n(tc)} & 100 \\\\", r"\bottomrule", r"\end{tabular*}",
           r"\end{table}"]
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
