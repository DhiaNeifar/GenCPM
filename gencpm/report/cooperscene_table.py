"""
Appendix table tab:cooperscene (generated from result files, no hand-typed numbers): GenCPM on real CooperScene data.
Per defense: CPM-level detection (AUC, precision, recall, F1, FPR, recall at 1% FPR) and end-to-end AP@0.5 on the
attacked frames after dropping flagged CPMs or filtering flagged objects, with the share of the attack-induced loss
recovered, and the AP@0.5 of the defense on the benign version of the same frames. Models marked * are trained on the
CARLA single-attacker collection and applied without retraining.
"""

import argparse
from pathlib import Path

import pandas as pd

from gencpm.report.common import fv, load_fusion, num, pct, table

ROWS = [  # (label, detector key, drop condition, filter condition)
    ("Plausibility rule", "plausibility", "def:plausibility", "ofilt:plausibility"),
    ("Consistency rule", "consistency", "def:consistency", "ofilt:consistency"),
    ("Association-jump rule", "rule-nn_med", None, None),
    ("LSTM$^\\ast$", "LSTM-transfer", "def:LSTM-transfer", None),
    ("GRU$^\\ast$", "GRU-transfer", "def:GRU-transfer", None),
    ("BiLSTM$^\\ast$", "BiLSTM-transfer", "def:BiLSTM-transfer", None),
    ("CNN--LSTM$^\\ast$", "CNN-LSTM-transfer", "def:CNN-LSTM-transfer", None),
    ("GBDT$^\\ast$", "GBDT-transfer", "def:GBDT-transfer", None),
    ("\\textbf{PILD}$^\\ast$", "PILD-transfer", "def:PILD-transfer", "ofilt:PILD-transfer"),
    ("GBDT, retrained", "GBDT-rules", "def:GBDT-rules", None),
    ("PILD, retrained", "PILD", "def:PILD", "ofilt:PILD"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True, help="CooperScene work dir (detection_summary.csv)")
    ap.add_argument("--fusion", required=True, help="CooperScene fusion result dir")
    ap.add_argument("--out", required=True)
    ap.add_argument("--bare", action="store_true",
                    help="caption and tabular only (\\captionof), to share a float page with another figure")
    a = ap.parse_args()
    d = pd.read_csv(Path(a.work) / "detection_summary.csv", index_col=0)
    g = load_fusion([a.fusion])
    s = "attacked(any)"
    att, ben = fv(g, s, "attack"), fv(g, s, "benign")

    def ap_rec(cond):
        if cond is None:
            return "--"
        v = fv(g, s, cond)
        return f"{v:.1f} ({round(100 * (v - att) / (ben - att)) + 0:d}\\%)"

    def ci(cond):
        return f"{fv(g, s, cond):.1f} [{fv(g, s, cond, 'lo'):.1f}, {fv(g, s, cond, 'hi'):.1f}]"

    head = [r"& \multicolumn{6}{c}{CPM-level detection (\%)} & \multicolumn{2}{c}{AP@0.5, loss recovered} & Benign \\",
            r"\cmidrule(lr){2-7}\cmidrule(lr){8-9}",
            r"Defense & AUC & Prec. & Rec. & F1 & FPR & Rec.\,1\% & Drop CPMs & Filter objects & AP@0.5 \\"]
    body = [r"\multicolumn{10}{l}{\textit{AP@0.5 with 95\% CI: ego only " + ci("ego_only") + "; benign cooperation "
            + ci("benign") + "; attack, no defense " + ci("attack") + r"}} \\", r"\midrule"]
    for name, key, dk, fk in ROWS:
        r = d.loc[key]
        det = [f"{r['auc']:.3f}", pct(r["precision@5"]), pct(r["tpr@5"]), pct(r["f1@5"]), pct(r["fpr@5"]),
               pct(r["tpr@1"])]
        bv = num(fv(g, s, "b" + dk), 1) if dk else "--"
        body.append(f"{name} & " + " & ".join(det + [ap_rec(dk), ap_rec(fk), bv]) + r" \\")
    body += [r"\midrule", "Oracle & -- & -- & -- & -- & -- & -- & " + ap_rec("oracle") + " & "
             + ap_rec("ofilt:oracle-object") + r" & -- \\"]
    cap = ("Real data: CooperScene validation and test scenes. CPM-level detection at the validation operating "
           "point, false-positive rate at most 5\\%; Rec.\\,1\\%: recall at a false-positive rate of at most 1\\%. "
           "AP@0.5 (\\%) on the frames in which a malicious CPM is fused, after discarding flagged CPMs or removing "
           "flagged objects, with the share of the attack-induced loss recovered; Benign: AP@0.5 of the defense on the "
           "benign version of the same frames. $^\\ast$trained on the CARLA single-attacker collection only, applied "
           "without retraining; retrained: trained on CooperScene.")
    if a.bare:
        tab = "\n".join([rf"\captionof{{table}}{{{cap}}}", r"\label{tab:cooperscene}", r"\footnotesize",
                         r"\begin{tabular}{lccccccccc}", r"\toprule"] + head + [r"\midrule"] + body
                        + [r"\bottomrule", r"\end{tabular}"])
    else:
        tab = table("table*", cap, "tab:cooperscene", "lccccccccc", head, body, size=r"\footnotesize")
    out = ["% Auto-generated by gencpm.report.cooperscene_table -- do not edit by hand.", tab]
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
